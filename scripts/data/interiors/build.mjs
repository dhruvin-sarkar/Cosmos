// Builds public/data/interiors/interiors.json from source.mjs + public/data/solar/bodies.json (mean radii).
// Usage: node scripts/data/interiors/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BODIES, REFERENCES } from './source.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const solar = JSON.parse(readFileSync(resolve(root, 'public/data/solar/bodies.json'), 'utf8'));
const radiusOf = new Map(solar.bodies.map(b => [b.id, b.radius?.meanKm ?? null]));
const round = (x, d = 5) => Number(x.toPrecision(d));

const errors = [];
const bodies = BODIES.map(b => {
  const radiusKm = radiusOf.get(b.body);
  if (radiusKm == null) errors.push(`${b.body}: no mean radius in bodies.json`);
  const R = radiusKm ?? b.layers[b.layers.length - 1].outerKm;
  let prev = 0;
  const layers = b.layers.map(l => {
    if (!(l.outerKm > prev)) errors.push(`${b.body}/${l.id}: outer radius not increasing`);
    for (const s of l.sources) if (!REFERENCES[s]) errors.push(`${b.body}/${l.id}: unknown source ${s}`);
    const out = {
      ...l,
      innerKm: prev,
      thicknessKm: round(l.outerKm - prev),
      fraction: round(l.outerKm / R),
      ...(l.outerRangeKm ? { fractionRange: l.outerRangeKm.map(x => round(x / R)) } : {}),
    };
    prev = l.outerKm;
    return out;
  });
  if (Math.abs(prev - R) / R > 0.001) errors.push(`${b.body}: outer layer ${prev} km != body radius ${R} km`);
  for (const h of b.howWeKnow) for (const s of h.sources) if (!REFERENCES[s]) errors.push(`${b.body} howWeKnow: unknown source ${s}`);
  return { ...b, radiusKm: R, layers };
});
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = {
  schemaVersion: 1,
  generated: new Date().toISOString().slice(0, 10),
  notes: [
    'Layers run from the centre outward. outerKm is the outer radius of the layer; fraction = outerKm / mean radius (public/data/solar/bodies.json).',
    'outerRangeKm / fractionRange give the spread of published models; model: true marks values that depend on an interior model rather than a direct measurement.',
    'Temperatures inside every body are model estimates except Earth\'s inner-core boundary (iron melting experiments) and the Sun\'s photosphere (observed).',
    'provenance: observed = measured directly (seismology, helioseismology); derived = computed from measurements (gravity, moment of inertia, induction); model = model-dependent.',
  ],
  references: REFERENCES,
  bodies,
};
mkdirSync(resolve(root, 'public/data/interiors'), { recursive: true });
writeFileSync(resolve(root, 'public/data/interiors/interiors.json'), JSON.stringify(out, null, 1) + '\n');

// docs/data/interiors.md: generated from the same source so the tables never drift from the JSON.
const fmtN = x => (x == null ? 'Unknown' : Math.abs(x) < 1 && x !== 0 ? String(Number(x.toPrecision(2))) : Number(x).toLocaleString('en-US', { maximumFractionDigits: 1 }));
const fmtR = r => (r == null ? 'Unknown' : r[0] === r[1] ? fmtN(r[0]) : `${fmtN(r[0])}-${fmtN(r[1])}`);
const md = [
  '# Planetary interiors (cutaway view data)',
  '',
  'Data behind the "Inside" cutaway (src/ui/interiors). Generated by `node scripts/data/interiors/build.mjs` from',
  '`scripts/data/interiors/source.mjs`; do not edit by hand. Output: `public/data/interiors/interiors.json`.',
  '',
  '## Conventions',
  '',
  ...out.notes.map(n => `- ${n}`),
  '- Body radii come from `public/data/solar/bodies.json` (mean radius); the outermost layer must end within 0.1% of it.',
  '- `model` = the boundary or values depend on an interior model; `outerRangeKm` gives the spread of published models.',
  '- The cutaway draws layers at true proportion, except layers thinner than 1.4% of the radius, which are drawn at',
  '  1.4% and disclosed in the view ("drawn thicker so they can be seen"). Colours are illustrative; the Temperature',
  '  mode shows model temperatures on a logarithmic Inferno scale spanning whole decades around the bodies on screen.',
  '- Unit tests: `src/ui/interiors/data.test.ts` (monotonic layers, radii match bodies.json, every layer cited,',
  '  headline values: PREM inner core 1221.5 km and outer core 3480 km, solar convection-zone base 0.713 R).',
  '',
  ...bodies.flatMap(b => [
    `## ${b.name} (${b.id}) - radius ${fmtN(b.radiusKm)} km`,
    '',
    b.lede,
    '',
    ...(b.uncertainty ? [`**Uncertainty:** ${b.uncertainty}`, ''] : []),
    '| Layer | Outer radius km (model range) | Fraction of R | State | Density kg/m3 | Temperature K | Provenance | Sources |',
    '|---|---|---|---|---|---|---|---|',
    ...[...b.layers].reverse().map(l =>
      `| ${l.name} | ${fmtN(l.outerKm)}${l.outerRangeKm ? ` (${fmtR(l.outerRangeKm)})` : ''} | ${l.fraction} | ${l.state} | ${fmtR(l.densityKgM3)} | ${fmtR(l.temperatureK)} | ${l.provenance}${l.model && l.provenance !== 'model' ? ', model-dependent' : ''} | ${l.sources.join(', ')} |`),
    '',
    'How we know: ' + b.howWeKnow.map(h => `${h.method} (${h.sources.join(', ')})`).join('; ') + '.',
    '',
  ]),
  '## References',
  '',
  ...Object.entries(REFERENCES).map(([k, r]) => `- **${k}**: ${r.cite}${r.doi ? `. doi:${r.doi}` : ''}`),
  '',
];
mkdirSync(resolve(root, 'docs/data'), { recursive: true });
writeFileSync(resolve(root, 'docs/data/interiors.md'), md.join('\n'));
console.log(`wrote ${bodies.length} bodies, ${bodies.reduce((n, b) => n + b.layers.length, 0)} layers`);
