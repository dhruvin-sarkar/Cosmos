#!/usr/bin/env node
/**
 * Generate docs/DATA_SOURCES.md, the data-source registry, from the merged dataset manifest.
 *
 *   node scripts/data/build-sources-doc.mjs
 *
 * Reads public/data/manifest.json (run scripts/data/build-manifest.mjs first; if the manifest is missing it is built
 * in memory from the manifest.part.json files). Output: a summary table plus one section per dataset. Re-runnable;
 * the file is fully regenerated, so edit the per-domain manifest.part.json files, not the output.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildManifest } from './build-manifest.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MANIFEST = join(ROOT, 'public', 'data', 'manifest.json');
const DATA_DIR = join(ROOT, 'public', 'data');
const DOMAIN_DOCS = join(ROOT, 'docs', 'data');
const OUT = join(ROOT, 'docs', 'DATA_SOURCES.md');

const PROVENANCE_GLYPH = { observed: 'observed', derived: 'derived', reconstructed: 'reconstructed', illustrative: 'illustrative' };

/** Escape text for a Markdown table cell. */
function cell(v) {
  return String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim() || '—';
}

/** Escape free text for a Markdown paragraph (only characters that would change structure at line start). */
function para(v) {
  const s = String(v ?? '').trim();
  return s ? s.replace(/\r?\n/g, ' ') : '_Not recorded._';
}

/** First sentence (or clause) of long free text, clipped for a summary table cell; the full text is in the section. */
function brief(v, max = 56) {
  const s = String(v ?? '').replace(/\s+/g, ' ').trim();
  const first = s.split(/(?<=[a-z]{3}[.;])\s|\s\(/)[0];
  return first.length > max ? `${first.slice(0, max - 1).trimEnd()}…` : first;
}

function formatBytes(n) {
  if (typeof n !== 'number' || !Number.isFinite(n)) return 'size unknown';
  if (n < 1024) return `${n} B`;
  const units = ['KB', 'MB', 'GB'];
  let v = n / 1024;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v.toFixed(v < 10 ? 2 : 1)} ${units[i]}`;
}

function shortName(name, max = 60) {
  const s = String(name ?? '').split(/[:(,]/)[0].trim() || String(name ?? '');
  return s.length > max ? `${s.slice(0, max - 1)}…` : s;
}

function retrievedDate(iso) {
  const t = Date.parse(iso);
  return Number.isNaN(t) ? cell(iso) : new Date(t).toISOString().slice(0, 10);
}

function anchor(id) {
  return String(id).toLowerCase().replace(/[^a-z0-9-]+/g, '-');
}

export function renderSourcesDoc(manifest, { domainsWithoutPart = [], domainDocs = new Set() } = {}) {
  const datasets = Object.values(manifest.datasets ?? {}).sort((a, b) => a.domain.localeCompare(b.domain) || a.id.localeCompare(b.id));
  const lines = [];
  lines.push('# Data sources');
  lines.push('');
  lines.push('<!-- Generated by scripts/data/build-sources-doc.mjs from public/data/manifest.json. Do not edit by hand:');
  lines.push('     change public/data/<domain>/manifest.part.json and re-run build-manifest.mjs + build-sources-doc.mjs. -->');
  lines.push('');
  lines.push(
    `Every dataset Cosmos ships, where it came from, and how it is processed. All data is snapshotted into \`public/data/\` ` +
      `so the exhibition build runs fully offline. Manifest generated ${cell(manifest.generated)}; ${datasets.length} dataset(s).`,
  );
  lines.push('');
  lines.push('Provenance classes follow the in-app legend: **observed** (measured and published), **derived** (computed from observed ' +
    'values by a stated model), **reconstructed** (a model fitted to sparse data, e.g. 3D structure from surveys), **illustrative** ' +
    '(artistic or schematic; not a measurement).');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| Dataset | Domain | Organization | Version | Retrieved | License | Class | Files |');
  lines.push('|---|---|---|---|---|---|---|---|');
  for (const d of datasets) {
    const bytes = (d.files ?? []).reduce((s, f) => s + (typeof f.bytes === 'number' ? f.bytes : 0), 0);
    lines.push(
      `| [${cell(shortName(d.name))}](#${anchor(d.id)}) | ${cell(d.domain)} | ${cell(shortName(d.organization, 48))} | ${cell(brief(d.version, 40))} | ` +
        `${retrievedDate(d.retrieved)} | ${cell(brief(d.license))} | ${cell(PROVENANCE_GLYPH[d.provenanceClass] ?? d.provenanceClass)} | ` +
        `${(d.files ?? []).length} (${formatBytes(bytes)}) |`,
    );
  }
  if (domainsWithoutPart.length) {
    lines.push('');
    lines.push(`Pending (data folder present, no manifest part yet): ${domainsWithoutPart.map(d => `\`${d}\``).join(', ')}.`);
  }
  lines.push('');

  let currentDomain = '';
  for (const d of datasets) {
    if (d.domain !== currentDomain) {
      currentDomain = d.domain;
      lines.push(`## Domain: ${currentDomain}`);
      lines.push('');
      if (domainDocs.has(currentDomain)) {
        lines.push(`Domain notes: [docs/data/${currentDomain}.md](data/${currentDomain}.md)`);
        lines.push('');
      }
    }
    lines.push(`<a id="${anchor(d.id)}"></a>`);
    lines.push(`### ${cell(d.name)}`);
    lines.push('');
    lines.push(`- **Dataset id:** \`${d.id}\``);
    lines.push(`- **Organization:** ${para(d.organization)}`);
    lines.push(`- **Version:** ${para(d.version)}`);
    lines.push(`- **Retrieved:** ${para(d.retrieved)}`);
    lines.push(`- **License:** ${para(d.license)}${d.licenseUrl ? ` (<${d.licenseUrl}>)` : ''}`);
    lines.push(`- **Provenance class:** ${para(d.provenanceClass)}`);
    lines.push(`- **Endpoint:** ${d.endpoint ? `<${d.endpoint}>` : '_Not recorded._'}`);
    lines.push(`- **Update cadence:** ${para(d.updateCadence)}`);
    lines.push(`- **Rate limits:** ${para(d.rateLimits)}`);
    lines.push(`- **Cache policy:** ${para(d.cachePolicy)}`);
    lines.push('');
    lines.push(`**Purpose.** ${para(d.purpose)}`);
    lines.push('');
    lines.push(`**Mechanism.** ${para(d.mechanism)}`);
    lines.push('');
    if (d.query) {
      lines.push('**Query.**');
      lines.push('');
      lines.push('```');
      lines.push(String(d.query).trim());
      lines.push('```');
      lines.push('');
    }
    lines.push(`**Normalization script.** ${para(d.normalization)}`);
    lines.push('');
    lines.push(`**Fallback.** ${para(d.fallback)}`);
    lines.push('');
    lines.push(`**Limitations.** ${para(d.limitations)}`);
    lines.push('');
    lines.push(`**Citation.** ${para(d.citation)}`);
    lines.push('');
    const fields = Array.isArray(d.fieldsUsed) ? d.fieldsUsed : [];
    lines.push(`**Fields used (${fields.length}).** ${fields.length ? fields.map(f => `\`${f}\``).join(', ') : '_Not recorded._'}`);
    lines.push('');
    lines.push('**Files.**');
    lines.push('');
    for (const f of d.files ?? []) {
      const recs = typeof f.records === 'number' ? `, ${f.records.toLocaleString('en-US')} records` : '';
      lines.push(`- \`public/${f.path}\` (${formatBytes(f.bytes)}${recs})`);
    }
    if (!(d.files ?? []).length) lines.push('- _None listed._');
    lines.push('');
  }
  return lines.join('\n');
}

function main() {
  let manifest;
  if (existsSync(MANIFEST)) {
    manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  } else {
    console.warn('public/data/manifest.json not found; building it in memory from manifest.part.json files.');
    manifest = buildManifest().manifest;
  }
  const domainsWithoutPart = existsSync(DATA_DIR)
    ? readdirSync(DATA_DIR, { withFileTypes: true })
        .filter(e => e.isDirectory() && !existsSync(join(DATA_DIR, e.name, 'manifest.part.json')))
        .map(e => e.name)
        .sort()
    : [];
  const domainDocs = new Set(
    existsSync(DOMAIN_DOCS) ? readdirSync(DOMAIN_DOCS).filter(f => f.endsWith('.md')).map(f => f.slice(0, -3)) : [],
  );
  writeFileSync(OUT, renderSourcesDoc(manifest, { domainsWithoutPart, domainDocs }) + '\n');
  console.log(`Wrote ${Object.keys(manifest.datasets ?? {}).length} dataset section(s) to docs/DATA_SOURCES.md`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
