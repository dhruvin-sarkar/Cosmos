/**
 * Bins the orbital catalogue snapshot (public/data/orbital/catalog.json, CelesTrak GP + SATCAT) into the debris lab's
 * altitude shells. Output: src/labs/debris/catalogShells.generated.json (small, imported by the lab).
 *   node src/labs/debris/tools/binCatalog.mjs
 * Altitude of an object = mean of its apogee and perigee altitudes (km above the WGS-72 equatorial radius, as in the
 * catalogue). LEO = apogee < 2000 km (catalogue definition). Shells: 200–2000 km in 50 km steps.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../..');
const cat = JSON.parse(readFileSync(resolve(root, 'public/data/orbital/catalog.json'), 'utf8'));
const fi = Object.fromEntries(cat.fields.map((f, i) => [f, i]));
const MIN = 200, MAX = 2000, STEP = 50;
const n = (MAX - MIN) / STEP;
const zero = () => new Array(n).fill(0);
const shells = { activePayload: zero(), inactivePayload: zero(), rocketBody: zero(), debris: zero(), unknown: zero() };
const events = { 'fengyun-1c-debris': zero(), 'cosmos-2251-debris': zero(), 'iridium-33-debris': zero() };
const eventTotals = { 'fengyun-1c-debris': 0, 'cosmos-2251-debris': 0, 'iridium-33-debris': 0 };
let below = 0, leo = 0, leoNoShape = 0;
for (const r of cat.rows) {
  const apo = r[fi.apogeeKm], per = r[fi.perigeeKm];
  const groups = r[fi.groups] ?? [];
  for (const g of groups) if (g in eventTotals) eventTotals[g]++;
  if (typeof apo !== 'number' || typeof per !== 'number') { leoNoShape++; continue; }
  if (!(apo < 2000)) continue;
  leo++;
  const h = (apo + per) / 2;
  if (h < MIN) { below++; continue; }
  const i = Math.min(n - 1, Math.floor((h - MIN) / STEP));
  const cls = r[fi.objectClass];
  const key = cls === 'payload' ? (r[fi.isActive] === true ? 'activePayload' : 'inactivePayload')
    : cls === 'rocket-body' ? 'rocketBody' : cls === 'debris' ? 'debris' : 'unknown';
  shells[key][i]++;
  for (const g of groups) if (g in events) events[g][i]++;
}
const out = {
  schemaVersion: 1,
  note: 'Generated by src/labs/debris/tools/binCatalog.mjs from public/data/orbital/catalog.json. Counts of tracked objects (roughly 10 cm and larger in LEO) by mean altitude.',
  catalogGenerated: cat.generated,
  source: cat.source,
  shellMinKm: MIN, shellMaxKm: MAX, shellStepKm: STEP,
  totals: cat.counts,
  leoCount: leo,
  leoBelowMinShell: below,
  withoutOrbitShape: leoNoShape,
  shells,
  breakupDebris: { totals: eventTotals, shells: events },
};
writeFileSync(resolve(here, '../catalogShells.generated.json'), JSON.stringify(out) + '\n');
console.log('leo', leo, 'below', below, 'events', JSON.stringify(eventTotals));
for (const k in shells) console.log(k, shells[k].reduce((a, b) => a + b, 0));
